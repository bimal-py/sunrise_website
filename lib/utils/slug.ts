/** "Pasni (rice feeding ceremony), Walling" → "pasni-rice-feeding-ceremony-walling". Latin letters only. */
export function slugify(text: string): string {
  return text
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}
