/** The built-in mark for each platform a social link can name (features/site/domain/social-link.ts). */
const PLATFORM_ICONS: Record<string, (props: IconProps) => ReactElement> = {
  facebook: FacebookIcon,
  youtube: YouTubeIcon,
  instagram: InstagramIcon,
  tiktok: TikTokIcon,
  x: XIcon,
  linkedin: LinkedInIcon,
  whatsapp: WhatsAppIcon,
};

/**
 * A social link's icon: the icon chosen for it in the dashboard (cleaned SVG, drawn as a mask
 * in the text colour) when there is one, else the platform's built-in mark, else a globe.
 * Decorative: the link around it carries the name (aria-label).
 */
export function SocialLinkIcon({ platform, iconSvg, className = "h-5 w-5" }: { platform: string; iconSvg?: string | null; className?: string }) {
  if (iconSvg) return <MaskIcon svg={iconSvg} className={className} />;
  const Icon = PLATFORM_ICONS[platform];
  if (Icon) return <Icon className={className} />;
  return <Globe className={className} strokeWidth={1.75} aria-hidden />;
}
